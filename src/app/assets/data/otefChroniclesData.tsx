// "כרוניקות העוטף" (Otef Chronicles) — מאגר שאלות חינוכי, נפרד וחדש.
// כל השאלות מבוססות אך ורק על תוכן שני המאמרים בפרויקט:
//   - early_history  (5,000 שנות עזה)
//   - otef_aza       (עוטף עזה, ההתיישבות בנגב והנגב הביזנטי)
// התמונות נשלפות מתיקיית public של הפרויקט (אותן תמונות שמופיעות במאמרים).
// סכמה גמישה התומכת בכמה סוגי שאלות, מתוך מחשבה על הרחבה עתידית.

function makeId(length = 6) {
  const possible = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
  let txt = ''
  for (let i = 0; i < length; i++) {
    txt += possible.charAt(Math.floor(Math.random() * possible.length))
  }
  return txt
}

export type ChronicleSource = 'early_history' | 'otef_aza'
export type ChronicleDifficulty = 'קל' | 'בינוני' | 'קשה'

export type ChronicleImage = { url: string; desc?: string }

type ChronicleBase = {
  id: string
  source: ChronicleSource
  difficulty: ChronicleDifficulty
  topic: string
  img?: ChronicleImage
}

// רב-ברירה — כולל את הווריאציות: מי אמר/עשה, זיהוי מיקום, סיבה ותוצאה.
export type MCQuestion = ChronicleBase & {
  kind: 'mc'
  subtype: 'general' | 'who' | 'location' | 'cause'
  question: string
  options: { id: string; answer: string; correct: boolean }[]
  explanation: string
}

// נכון / לא נכון.
export type TFQuestion = ChronicleBase & {
  kind: 'tf'
  statement: string
  answerTrue: boolean
  explanation: string
}

// סידור על ציר הזמן — לגרור/להקיש לפי הסדר הכרונולוגי הנכון.
export type OrderQuestion = ChronicleBase & {
  kind: 'order'
  question: string
  items: { id: string; label: string }[]
  correctOrder: string[] // מזהי הפריטים לפי הסדר הנכון
  explanation: string
}

export type ChronicleQuestion = MCQuestion | TFQuestion | OrderQuestion

const mc = (
  source: ChronicleSource,
  difficulty: ChronicleDifficulty,
  topic: string,
  subtype: MCQuestion['subtype'],
  question: string,
  options: [string, boolean][],
  explanation: string,
  img?: ChronicleImage
): MCQuestion => ({
  id: makeId(),
  kind: 'mc',
  source,
  difficulty,
  topic,
  subtype,
  question,
  options: options.map(([answer, correct]) => ({ id: makeId(), answer, correct })),
  explanation,
  img,
})

const tf = (
  source: ChronicleSource,
  difficulty: ChronicleDifficulty,
  topic: string,
  statement: string,
  answerTrue: boolean,
  explanation: string,
  img?: ChronicleImage
): TFQuestion => ({
  id: makeId(),
  kind: 'tf',
  source,
  difficulty,
  topic,
  statement,
  answerTrue,
  explanation,
  img,
})

const order = (
  source: ChronicleSource,
  difficulty: ChronicleDifficulty,
  topic: string,
  question: string,
  ordered: string[], // כבר בסדר הכרונולוגי הנכון
  explanation: string,
  img?: ChronicleImage
): OrderQuestion => {
  const items = ordered.map(label => ({ id: makeId(), label }))
  return {
    id: makeId(),
    kind: 'order',
    source,
    difficulty,
    topic,
    question,
    items,
    correctOrder: items.map(it => it.id),
    explanation,
    img,
  }
}

